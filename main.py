h1 = int(input("Напишите 1 число: "))
h2 = int(input("Напишите 1 число: "))
hd = input("Какое действия?: ")
if hd == "+":
    Ot = h1 + h2
    print(f"{h1} + {h2} = {Ot}")
if hd == "-":
    Ot = h1 - h2
    print(f"{h1} - {h2} = {Ot}")
if hd == "/":
    Ot = h1 / h2
    print(f"{h1} / {h2} = {Ot}")
if hd == "*":
    Ot = h1 * h2
    print(f"{h1} * {h2} = {Ot}")
